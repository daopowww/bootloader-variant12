sti

mov ax, 0013h
int 10h
mov ax, 0A000h
mov es, ax

mov di, 134 * 320 + 216
mov dx, -20

row:
    mov si, dx
    imul si, si
    shl si, 2
    mov bx, -40

pixel:
    mov ax, bx
    imul ax, ax
    add ax, si
    cmp ax, 1600
    ja next_pixel
    mov byte [es:di], 11

next_pixel:
    inc di
    inc bx
    cmp bx, 41
    jl pixel

    add di, 320 - 81
    inc dx
    cmp dx, 21
    jl row

; Синий фон под надписью
xor ax, ax
mov ds, ax
cld
mov di, 12 * 320 + 12
mov ax, 0101h
mov dx, 56
panel_row:
    mov cx, 98
    rep stosw
    add di, 320 - 196
    dec dx
    jnz panel_row

; Каждая строка начинается со смещения в видеопамяти
mov si, labels
text_row:
    lodsw
    test ax, ax
    jz stop
    mov di, ax
text_char:
    lodsb
    cmp al, 255
    je text_row
    call draw_char
    jmp text_char

; Символ 5 × 7. Каждый пиксель увеличен до 2 × 2.
draw_char:
    push si
    push di
    xor ah, ah
    imul bx, ax, 7
    mov si, font
    add si, bx
    mov bp, 7
glyph_row:
    lodsb
    mov cx, 5
glyph_pixel:
    test al, 16
    jz glyph_next
    mov word [es:di], 0E0Eh
    mov word [es:di+320], 0E0Eh
glyph_next:
    shl al, 1
    add di, 2
    loop glyph_pixel
    add di, 640 - 10
    dec bp
    jnz glyph_row
    pop di
    add di, 12
    pop si
    ret

labels:
    dw 17 * 320 + 18
    db 1,2,3,4,5,6,7,8,255                  ; МИНГАЗОВ
